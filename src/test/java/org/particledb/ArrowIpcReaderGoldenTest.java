    @Test
    void truncatedStreamsFailOrYieldWholeBatchesOnly() throws Exception {
        // Cut every golden at every byte: the reader either throws its own
        // IpcException or returns the rows of the whole batches before the
        // cut -- never a wrong value, never another exception type.
        for (GoldenCases.Case c : GoldenCases.ALL) {
            byte[] p = golden(c.name);
            ArrowDecoder.Decoded full = ArrowIpcReader.decode(p);
            for (int cut = 0; cut < p.length; cut++) {
                byte[] t = Arrays.copyOf(p, cut);
                ArrowDecoder.Decoded d;
                try {
                    d = ArrowIpcReader.decode(t);
                } catch (ArrowIpcReader.IpcException expected) {
                    continue;
                }
                if (cut == 0) continue; // empty payload: empty result
                assertTrue(d.rows.size() <= full.rows.size(), c.name + " cut " + cut);
                for (int r = 0; r < d.rows.size(); r++) {
                    assertTrue(GoldenCases.cellEquals(full.rows.get(r)[0], d.rows.get(r)[0]), c.name + " cut " + cut);
                }
            }
        }
    }

    @Test
    void corruptedStreamsNeverEscapeAsAnotherException() throws Exception {
        java.util.Random rnd = new java.util.Random(20261026L);
        for (GoldenCases.Case c : GoldenCases.ALL) {
            byte[] p = golden(c.name);
            for (int i = 0; i < 2000; i++) {
                byte[] t = p.clone();
                int flips = 1 + rnd.nextInt(3);
                for (int k = 0; k < flips; k++) t[rnd.nextInt(t.length)] ^= (byte) (1 << rnd.nextInt(8));
                try {
                    ArrowIpcReader.decode(t);
                } catch (ArrowIpcReader.IpcException | ArithmeticException | java.time.DateTimeException ok) {
                    // rejected loudly, or a value out of the Java type's range
                } catch (RuntimeException | OutOfMemoryError e) {
                    fail(c.name + " flip " + i + ": " + e);
                }
            }
        }
    }

    @Test
    void aBufferOffsetThatOverflowsIsRefused() {
        // off + len wraps negative for these; the check must not add them.
        for (long off : new long[] {Long.MAX_VALUE, Long.MAX_VALUE - 7, 9, -1}) {
            assertThrows(ArrowIpcReader.IpcException.class,
                    () -> ArrowIpcReader.decode(GoldenMutations.int32(false, off)), "offset " + off);
        }
        assertEquals(0, ArrowIpcReader.decode(GoldenMutations.int32(false, 0)).rows.get(0)[0]);
    }

    @Test
    void aZeroWidthColumnCannotClaimBillionsOfRows() {
        // Positive control: a few zero-width values decode (to empty arrays).
        ArrowDecoder.Decoded small = ArrowIpcReader.decode(GoldenMutations.zeroWidthBinary(3));
        assertEquals(3, small.rows.size());
        assertArrayEquals(new byte[0], (byte[]) small.rows.get(2)[0]);
        ArrowIpcReader.IpcException e = assertThrows(ArrowIpcReader.IpcException.class,
                () -> ArrowIpcReader.decode(GoldenMutations.zeroWidthBinary(Integer.MAX_VALUE - 8)));
        assertTrue(e.getMessage().contains("claims"), e.getMessage());
    }

    @Test
    void rowsSharingADictionaryEntryDoNotShareMutableValues() throws Exception {
        // dict_list_int32_int8: rows 0 and 2 index the same dictionary entry.
        ArrowDecoder.Decoded d = ArrowIpcReader.decode(golden("dict_list_int32_int8"));
        Object[] row0 = (Object[]) d.rows.get(0)[0];
        Object[] row2 = (Object[]) d.rows.get(2)[0];
        assertNotSame(row0, row2);
        row0[0] = 99;
        assertEquals(1, row2[0], "mutating one row's value changed another row");
    }

    @Test
    void entryPointWrapsReaderFailures() {
        RuntimeException e = assertThrows(RuntimeException.class,
                () -> ArrowDecoder.decodePositional(new byte[] {(byte) 0xFF, (byte) 0xFF, (byte) 0xFF, (byte) 0xFF, 9, 0, 0, 0}));
        assertTrue(e.getMessage().startsWith("ParticleDB JDBC: Arrow IPC decode failed"), e.getMessage());
        assertTrue(ArrowDecoder.decodeColumnNames(new byte[] {1, 2, 3}).isEmpty());
        assertTrue(ArrowDecoder.decodePositional(new byte[0]).rows.isEmpty());
    }

    @Test
    void compressedBodiesAndUnsupportedTypesAreRefusedByName() throws Exception {
        // A record batch whose header carries a BodyCompression table.
        // Positive control: the same hand-built stream without compression decodes.
        assertEquals(0, ArrowIpcReader.decode(GoldenMutations.int32(false)).rows.get(0)[0]);
        byte[] compressed = GoldenMutations.int32(true);
        ArrowIpcReader.IpcException e = assertThrows(ArrowIpcReader.IpcException.class,
                () -> ArrowIpcReader.decode(compressed));
        assertTrue(e.getMessage().contains("compressed"), e.getMessage());
        byte[] union = GoldenMutations.schemaOfType(14);
        e = assertThrows(ArrowIpcReader.IpcException.class, () -> ArrowIpcReader.decode(union));
        assertTrue(e.getMessage().contains("Union"), e.getMessage());
        byte[] view = GoldenMutations.schemaOfType(24);
        e = assertThrows(ArrowIpcReader.IpcException.class, () -> ArrowIpcReader.decode(view));
        assertTrue(e.getMessage().contains("Utf8View"), e.getMessage());
    }
